#!/usr/bin/env python3
"""Extracts translated guest functions that the shard build leaves out.

The base translation (upstream/generated/base_translation_sources.bin) holds a translated
source for every guest function, but the shard graph omits the ~570 that upstream replaces
with native PC code. Most of those we replace too (hle_*.cpp). A few are ordinary game code
whose original behaviour is exactly what the Vita build wants; this script pulls their
sources out into one build-generated translation unit and appends a static registration
for each, so the runtime finds them through find_hle_native without any link-time
reference (the host builds have no translated code at all).

The output is generated from the user's own disc and must never be committed.

usage: extract_translated.py <base_translation_sources.bin> <out.cpp> <ADDR> [ADDR...]
"""

import struct
import sys


def read_entries(path, wanted):
    found = {}
    with open(path, "rb") as f:
        magic = f.read(8)
        if magic != b"MKWSRC01":
            raise SystemExit("%s: not a MKWSRC01 file" % path)
        version, count = struct.unpack("<II", f.read(8))
        if version != 1:
            raise SystemExit("%s: unsupported version %u" % (path, version))
        for _ in range(count):
            entry, name_len = struct.unpack("<II", f.read(8))
            name = f.read(name_len).decode("utf-8", "replace")
            (size,) = struct.unpack("<I", f.read(4))
            f.seek(32, 1)  # sha256
            if entry in wanted:
                found[entry] = (name, f.read(size).decode("utf-8"))
                if len(found) == len(wanted):
                    break
            else:
                f.seek(size, 1)
    return found


def main(argv):
    if len(argv) < 4:
        raise SystemExit(__doc__)
    src_bin, out_path = argv[1], argv[2]
    wanted = [int(a, 16) for a in argv[3:]]
    found = read_entries(src_bin, set(wanted))
    missing = [a for a in wanted if a not in found]
    if missing:
        raise SystemExit("not in %s: %s" % (src_bin, " ".join("%08X" % a for a in missing)))

    parts = [
        "// Generated by scripts/extract_translated.py from the user's base translation.\n"
        "// Do not edit and do not commit.\n"
        '#include "abi_bridge.h"\n'
    ]
    for addr in wanted:
        name, source = found[addr]
        symbol = "func_%08X" % addr
        if ('extern "C" void %s(' % symbol) not in source:
            raise SystemExit("%s does not define %s" % (name, symbol))
        parts.append('#line 1 "%s"\n' % name)
        parts.append(source)
        if not source.endswith("\n"):
            parts.append("\n")

    parts.append(
        "\n#line 1 \"extra_translated_registration\"\n"
        'extern "C" void mkwv_register_extra_native(uint32_t address, void (*fn)(CpuContext*));\n'
        "namespace {\n"
        "struct ExtraTranslatedRegistrar {\n"
        "    ExtraTranslatedRegistrar() {\n"
    )
    for addr in wanted:
        parts.append("        mkwv_register_extra_native(0x%08Xu, func_%08X);\n" % (addr, addr))
    parts.append("    }\n} g_extra_translated_registrar;\n} // namespace\n")

    with open(out_path, "w") as f:
        f.write("".join(parts))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
